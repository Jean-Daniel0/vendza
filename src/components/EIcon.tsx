export function EIcon({ name, className = '' }: { name: string; className?: string }) {
  const C = ICONS[name];
  if (!C) return null;
  const fill = name === 'Star' ? ' fill-current' : '';
  return <C aria-hidden="true" className={`inline-block h-[1.1em] w-[1.1em] shrink-0 align-[-0.2em]${fill} ${className}`} />;
}

/** Affiche un texte en remplaçant les repères [[NomIcône]] par la vraie icône. Tout autre type de contenu passe tel quel. */
export function RichText({ text, className }: { text?: React.ReactNode; className?: string }) {
  if (typeof text !== 'string') return <>{text}</>;
  const parts = text.split(/\[\[(\w+)\]\]/g);
  if (parts.length === 1) return <>{text}</>;
  return (
    <>
      {parts.map((p, i) => (
        <React.Fragment key={i}>{i % 2 === 1 ? <EIcon name={p} className={className} /> : p}</React.Fragment>
      ))}
    </>
  );
}
